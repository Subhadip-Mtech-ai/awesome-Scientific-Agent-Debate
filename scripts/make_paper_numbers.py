def main():
    os.makedirs("paper", exist_ok=True)
    lines = [
        "% AUTO-GENERATED by scripts/make_paper_numbers.py — do not edit by hand",
        "% Usage in LaTeX: \\N{QualC} or \\NQualC expands to 3.47",
        "",
        "\\makeatletter",
        "\\providecommand{\\N}[1]{%",
        "  \\@ifundefined{num@#1}{%",
        "    \\@ifundefined{#1}{%",
        "      \\textbf{??#1??}%",
        "    }{\\csname #1\\endcsname}%",
        "  }{\\csname num@#1\\endcsname}%",
        "}",
        "\\newcommand{\\setnum}[2]{%",
        "  \\@namedef{num@#1}{#2}%",
        "  \\expandafter\\gdef\\csname N#1\\endcsname{#2}%",
        "}",
        "\\makeatother",
        "",
    ]
    for name, val in NUMBERS.items():
        lines.append(f"\\setnum{{{name}}}{{{val}}}")

    output_path = os.path.join("paper", "numbers.tex")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{output_path} written ({len(NUMBERS)} macros)")

if __name__ == "__main__":
    main()
